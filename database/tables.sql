CREATE TABLE IF NOT EXISTS Hutch
(
    uID INTEGER PRIMARY KEY REFERENCES User(uID) ON DELETE CASCADE ON UPDATE CASCADE,
    babyRabbit INTEGER NOT NULL >=0 DEFAULT 8,
    smallRabbit INTEGER NOT NULL >=0 DEFAULT 0,
    bigRabbit INTEGER NOT NULL >=0 DEFAULT 0,
    adultRabbitMale INTEGER NOT NULL >=0 DEFAULT 0,
    adultRabbitFemale INTEGER NOT NULL >=0 DEFAULT 0,
    lastMeal DATE NOT NULL DEFAULT CURRENT_DATE,
    lastDrink DATE NOT NULL DEFAULT CURRENT_DATE,
    timeSick DATE DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS Cow
(
    aID INTEGER PRIMARY KEY REFERENCES Animal(aID) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS Event
(
    eID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    uID INTEGER NOT NULL REFERENCES "User"(uID) ON DELETE CASCADE ON UPDATE CASCADE,
    text VARCHAR(200) NOT NULL,
    dateEvent TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Market
(
    uID INTEGER NOT NULL REFERENCES "User"(uID) ON DELETE CASCADE ON UPDATE CASCADE,
    productID INTEGER NOT NULL REFERENCES Product(productID) ON DELETE CASCADE ON UPDATE CASCADE,
    price FLOAT NOT NULL,
    PRIMARY KEY (uID, productID)
);

CREATE TABLE IF NOT EXISTS Cooperative
(
    uID INTEGER NOT NULL REFERENCES "User"(uID) ON DELETE CASCADE ON UPDATE CASCADE,
    productID INTEGER NOT NULL REFERENCES Product(productID) ON DELETE CASCADE ON UPDATE CASCADE,
    isOpen BOOLEAN,
    PRIMARY KEY (uID, productID)
);
