SET search_path TO TinyFarm;

/* Enum types for animal subtypes */
CREATE TYPE chickenTypeEnum AS ENUM ('poussin', 'poule', 'coq');
--CREATE TYPE rabbit_type_enum AS ENUM ('lapereau', 'lapin');

CREATE TABLE IF NOT EXISTS "User"
(
    uID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nom VARCHAR(20),
    sexe VARCHAR(20),
    ecus INTEGER,
    level INTEGER DEFAULT 1
);

CREATE TABLE IF NOT EXISTS Product
(
    productID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    description TEXT,
    collection BOOLEAN,
    price FLOAT,
    coef INTEGER DEFAULT 1
);

CREATE TABLE IF NOT EXISTS Transactions
(
    tID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    seller INTEGER NOT NULL REFERENCES "User"(uID) ON DELETE CASCADE ON UPDATE CASCADE,
    buyer INTEGER NOT NULL REFERENCES "User"(uID) ON DELETE CASCADE ON UPDATE CASCADE,
    product INTEGER NOT NULL REFERENCES Product(productID) ON DELETE CASCADE ON UPDATE CASCADE,
    quantite INTEGER NOT NULL CHECK (quantite > 0),
    prixTotal FLOAT NOT NULL CHECK (prixTotal >= 0),
    dateTransaction TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CHECK (seller != buyer)
);

CREATE TABLE IF NOT EXISTS Stock
(
    uID INTEGER NOT NULL REFERENCES "User"(uID) ON DELETE CASCADE ON UPDATE CASCADE,
    productID INTEGER NOT NULL REFERENCES Product(productID) ON DELETE CASCADE ON UPDATE CASCADE,
    quantity INTEGER DEFAULT 0 CHECK (quantity >= 0),
    PRIMARY KEY (uID, productID)
);

CREATE TABLE IF NOT EXISTS Desktop
(
    uID INTEGER NOT NULL REFERENCES "User"(uID) ON DELETE CASCADE ON UPDATE CASCADE,
    productID INTEGER NOT NULL REFERENCES Product(productID) ON DELETE CASCADE ON UPDATE CASCADE,
    quantity INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    PRIMARY KEY (uID, productID)
);

CREATE TABLE IF NOT EXISTS Animal
(
    uID INTEGER NOT NULL REFERENCES "User"(uID) ON DELETE CASCADE ON UPDATE CASCADE,
    aID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    clean BOOLEAN,
    healthy BOOLEAN,
    age INTEGER,
    weight FLOAT,
    aGender BOOL
);

CREATE TABLE IF NOT EXISTS Chicken
(
    aID INTEGER PRIMARY KEY REFERENCES Animal(aID) ON DELETE CASCADE ON UPDATE CASCADE,
    chickenType chickenTypeEnum,
    fasting INTEGER DEFAULT 0
);

